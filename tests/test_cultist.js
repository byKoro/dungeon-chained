import assert from 'node:assert/strict';
import { SpawnSystem } from '../js/systems/SpawnSystem.js';
import { CultistEnemy } from '../js/entities/CultistEnemy.js';
import { CULTIST } from '../js/config/CultistConfig.js';
import { editorEnemyTypes } from '../js/editor2/ContentCatalog.js';
const spawn = new SpawnSystem({ assets: { get: () => ({ complete: true, naturalWidth: 1400 }) }, bloodCanvas: { palette: [] } });
const create = () => spawn.createEnemy(0, 0, 1, 'cultist');
const player = (x, y = 0) => ({ x, y, lives: 3, hitRadius: 16, hits: 0, takeDamage() { this.hits++; return true; } });
const step = (enemy, players, n = 1) => { for (let i = 0; i < n; i++) enemy.update(players, () => {}); };
const untilAttack = (e, ps) => { for (let i = 0; i < 500 && e.state !== 'attack'; i++) step(e, ps); assert.equal(e.state, 'attack'); };
assert.ok(create() instanceof CultistEnemy);
assert.ok(editorEnemyTypes().some(t => t.key === 'cultist'));
const retreat = create(), near = player(80), far = player(700);
step(retreat, [near, far], 20);
assert.ok(retreat.x < 0, 'retreat from nearby player');
assert.equal(retreat.markedPosition, null, 'do not stop to cast while crowded');
const approach = create(); step(approach, [player(600), player(800)], 20);
assert.ok(approach.x > 0, 'approach distant players');
const custom = create(); custom.preferredDistance = 350;
step(custom, [player(240), player(600)], 20);
assert.ok(custom.x < 0, 'public preferredDistance controls retreat');
const safe = create(); safe.players = [player(80)];
safe.setNavigationFloor(Array.from({ length: 7 }, () => Array(7).fill(0)), { minX: -100, minY: -100 }, [{ col: 2, row: 3 }]);
const waypoint = safe._chaseWaypoint(safe.players[0]);
assert.ok(!waypoint || safe._isWalkable(waypoint.x, waypoint.y));

const caster = create(), target = player(440), other = player(600);
step(caster, [target, other]);
assert.equal(caster.state, 'windup');
assert.deepEqual(caster.markedPosition, { x: 440, y: 0 });
target.x = 570;
untilAttack(caster, [target, other]);
step(caster, [target, other], 60);
assert.equal(target.hits, 0, 'moving off marked position dodges fire');
assert.deepEqual(caster.markedPosition, { x: 440, y: 0 }, 'marker does not track target');
other.x = 440;
step(caster, [target, other], 5);
assert.equal(other.hits, 1, 'pillar damages players entering marked position');
step(caster, [target, other], 6);
assert.equal(other.hits, 1, 'one successful hit per player per pillar');
const victim = player(440), second = player(450);
const aoe = create(); untilAttack(aoe, [victim, second]); step(aoe, [victim, second], 60);
assert.equal(victim.hits, 1); assert.equal(second.hits, 1);
const interrupted = create(); step(interrupted, [player(440), player(600)]);
interrupted.takeHit(1, { dirX: -1, dirY: 0 }); step(interrupted, [player(440), player(600)]);
assert.equal(interrupted.markedPosition, null, 'stagger cancels cast');
const frozen = create(); frozen.beginFrozenSpawn(20); step(frozen, [player(440)], 10);
assert.equal(frozen.markedPosition, null);
const dead = create(); dead.startDying();
assert.equal(dead.dyingDuration, 70);
assert.equal(dead._currentAnim().row, 5);
step(dead, [], 69); assert.equal(dead.readyToGib, false);
step(dead, []); assert.equal(dead.readyToGib, true);
assert.deepEqual(dead.explodeIntoGibs(), []);
assert.equal(create().sprite.rows.attack.row, 3);
const ignored = create();
step(ignored, [player(440), { ...player(20), lives: 0 }]);
assert.deepEqual(ignored.markedPosition, { x: 440, y: 0 }, 'ignore dead targets');
const none = create(); step(none, [], 10);
assert.equal(none.markedPosition, null, 'no casts without valid targets');
const outOfBand = create(); step(outOfBand, [player(550), player(800)]);
assert.equal(outOfBand.state, 'chase', 'approach desired range before casting');

console.log('Cultist: distance, fixed target, dodge, AoE, stagger, spawn and death passed.');
